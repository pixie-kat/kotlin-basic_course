/*
Operations with Collections
The Iterable interface gives you many functions for working with collections.
Here are some of the most important:
all { ... }: true if all items match a rule
any { ... }: true if any item matches a rule
asSequence(): turns the collection into a sequence
average(): average value of number items
chunked(size): splits the collection into pieces of a certain size
contains(element): true if the item is present
count(): number of items
distinct(): only unique items
drop(n): skips the first n items
elementAt(index): gets an item by index
filter { ... }: keeps only items that match a rule
find { ... }: finds the first item that matches a rule
first(), last(): gets the first or last item
forEach { ... }: does something with every item
groupBy { ... }: groups items by a key
indexOf(element): index of an item
intersect(other): items present in both collections
joinToString(): turns the collection into a string
map { ... }: changes each item with a function
maxOrNull(), minOrNull(): maximum or minimum value
plus(element), minus(element): adds or removes an item, returns a new collection
reduce { ... }: combines items into one value
shuffled(): mixes the order of items
sorted(): sorts items
sum(): total sum of items
take(n): takes the first n items
toList(), toSet(), toMap(): changes the collection to another type
union(other): unique items from both collections
 */